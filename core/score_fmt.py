# -*- coding: utf-8 -*-
"""배점 숫자 → 표시 문자열. **모든 소비자가 이걸 써야 한다.**

⭐ 왜 중립 모듈인가(2026-08-08 적대리뷰):
처음엔 `hwp_com_writer` 안에 두고 렌더 4곳에만 적용했는데, `score` 를 문자열로 만드는
소비자는 그 외에도 있었다 — **DeepSeek 프롬프트 2곳**(`solution_generator` 의 소문항
배점·문항 배점)과 HWP 미설치 폴백(`hwpx_writer`). 그래서 exe 는 모델에 `(배점 3.0점)`
을 보내고 웹은 `(배점 3점)` 을 보내, **생성되는 정답·해설이 갈리고 그게 그대로 .hwp 에
렌더**됐다. 렌더만 맞춰서는 소용이 없다.

`hwp_com_writer` 를 import 하면 렌더 스택(COM 계열)이 딸려 오므로, 프롬프트 생성기가
쓸 수 있도록 의존성 없는 모듈로 분리한다.
"""
from __future__ import annotations


def score_str(score) -> str:
    """배점 → 표시 문자열.

    ⭐⭐ **문자열이면 그대로 쓴다** — 그게 인쇄된 표기다(2026-08-20). 배점이 ``3.0`` 으로
    인쇄된 시험지와 ``4`` 로 인쇄된 시험지가 **같은 소수 사다리 안에서** 공존한다:

      · 대륜고 공수2 #8 = ``[3.0점]``  (사다리 2.3~3.6, 8번만 정수)
      · 대진고 공수2 #3 = ``[4점]``    (사다리 3.8~4.8, 3·4번만 정수)

    숫자만 보고는 절대 구분할 수 없으므로(JSON 이 3 과 3.0 을 구분 못 하는 것과 별개로
    **원본 인쇄가 실제로 다르다**), 파서와 OCR 은 인쇄된 표기를 **문자열로** 보존하고
    여기서는 그대로 내보낸다.

    숫자로 올 때(표기 정보가 없을 때)는 종전대로 정수는 소수점을 떼고 소수는 그대로:
      ① OCR 이 ``3.0`` 을 주면 ``str(3.0)`` = "3.0" 이라 ``[3.0점]`` 으로 찍히는데,
         표기 정보가 없는 이상 정수 배점 시험지가 다수다.
      ② JSON 은 ``3`` 과 ``3.0`` 을 타입으로 구분하지 못한다 — exe 는 파이썬 json 이
         파싱한 float 를, 웹은 두 번 직렬화되며 int 로 접힌 값을 본다. 표시 시점
         정규화가 양쪽을 같게 만드는 유일한 방법이다.
    """
    if isinstance(score, str):
        s = score.strip()
        if s:
            return s
    try:
        f = float(score)
    except (TypeError, ValueError):
        return str(score)
    return str(int(f)) if f.is_integer() else str(score)
