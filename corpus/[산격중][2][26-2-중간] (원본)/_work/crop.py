import json
from PIL import Image
B={1:[(1,165,595,612,840),(2,165,898,612,1218),(3,165,1278,612,1500),(4,614,455,1062,832),(5,614,898,1062,1148),(6,614,1243,1062,1492)],
2:[(7,130,352,587,702),(8,130,778,587,1152),(9,130,1213,587,1482),(10,585,352,1037,637),(11,585,773,1037,1017),(12,585,1208,1037,1467)],
3:[("s1",145,455,602,885),("s2",145,1093,602,1422),("s3",600,348,1047,757),("s4",600,823,1047,1312)],
4:[(13,160,358,612,522),(14,160,683,612,1018),(15,160,1158,612,1422),(16,610,353,1062,712),(17,610,853,1062,1437)]}
out=[]
for p,L in B.items():
    im=Image.open(f'pages/p{p}_r.png'); W,H=im.size
    for m,(n,x0,y0,x1,y1) in enumerate(L,1):
        box=(x0*3,y0*3,x1*3,y1*3)
        im.crop(box).save(f'crop/p{p}_c{m}.png')
        out.append({"page":p,"number":n,"bbox":[round(box[0]/W,4),round(box[1]/H,4),round(box[2]/W,4),round(box[3]/H,4)]})
json.dump(out,open('crop/crops.json','w',encoding='utf-8'),ensure_ascii=False,indent=1)
