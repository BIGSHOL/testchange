def T(v):
    return {"type": "text", "value": v}


def E(v):
    return {"type": "equation", "value": v}


def F(v):
    return {"type": "figure", "value": v}


def ch(*items):
    out = []
    for i, it in enumerate(items, 1):
        if isinstance(it, list):
            out.append({"number": i, "contents": it})
        else:
            out.append({"number": i, "contents": [E(str(it))]})
    return out


def Q(n, s, contents, choices=None, **kw):
    q = {"number": n, "score": s, "contents": contents}
    if choices:
        q["choices"] = choices
    q.update(kw)
    return q


def listing(*xs):
    """쉼표 나열 — 항목마다 수식 객체, 사이는 평문 ', '(한 수식에 쉼표를 넣으면 나열이 뭉개진다)."""
    out = []
    for i, x in enumerate(xs):
        if i:
            out.append(T(", "))
        out.append(E(str(x)))
    return out


